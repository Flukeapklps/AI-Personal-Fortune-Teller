// Regenerates src/lib/fortune/cny-table.ts (Chinese New Year dates 1900–2100).
// Usage: node scripts/generate-cny-table.mjs
//
// Source: lunar-javascript (high-precision astronomical Chinese calendar, dev dependency).
// We deliberately do NOT use ICU's Intl "chinese" calendar for the table: its
// approximation misplaces new moons that fall within minutes of Beijing midnight
// (it reports 1954-02-04, 2027-02-07 and 2030-02-02; the published dates are
// 1954-02-03, 2027-02-06 and 2030-02-03). The script prints any ICU disagreements.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { Lunar } = require("lunar-javascript");

const icu = new Intl.DateTimeFormat("en-u-ca-chinese", { month: "numeric", day: "numeric", timeZone: "UTC" });

const dates = [];
for (let y = 1900; y <= 2100; y++) {
  const s = Lunar.fromYmd(y, 1, 1).getSolar();
  if (s.getYear() !== y) throw new Error(`Unexpected year for ${y}`);
  const mmdd = String(s.getMonth()).padStart(2, "0") + String(s.getDay()).padStart(2, "0");
  const parts = icu.formatToParts(new Date(Date.UTC(y, s.getMonth() - 1, s.getDay())));
  const icuIsNewYear = parts.find((p) => p.type === "month")?.value === "1" && parts.find((p) => p.type === "day")?.value === "1";
  if (!icuIsNewYear) console.warn(`note: ICU disagrees for ${y} (using ${y}-${mmdd})`);
  dates.push(JSON.stringify(mmdd));
}

let src =
  "// Chinese New Year (first day of the first lunar month) for each Gregorian year 1900–2100, as MMDD.\n" +
  "// Generated by scripts/generate-cny-table.mjs from lunar-javascript (astronomical calendar).\n" +
  "// Do not edit by hand.\n" +
  "export const CNY_START_YEAR = 1900;\nexport const CNY_DATES: readonly string[] = [\n";
for (let i = 0; i < dates.length; i += 10) src += "  " + dates.slice(i, i + 10).join(", ") + ",\n";
src += "];\n";
writeFileSync(new URL("../src/lib/fortune/cny-table.ts", import.meta.url), src);
console.log(`Wrote ${dates.length} years`);
